#!/usr/bin/python3
import ipaddress
import os
import re
import signal
import sys
import time
from subprocess import check_call, Popen

def initialize_logdir(app='coneshare'):
    """create log directory for app
            /var/log/supervisor
            /var/log/nginx
    """

    log_dir = os.environ['LOG_DIR']

    for dirname in ['nginx']:
        check_call('mkdir -p %s/%s' % (log_dir, dirname), shell=True)

    check_call('chown -R coneshare:coneshare %s' % (log_dir), shell=True)
    check_call('chmod -R 0755 %s' % (log_dir), shell=True)

def change_ugid():
    """Change the UID/GID of the existing container user at runtime
    so they match the host user that owns the mounted files.
    """
    puid = os.getenv("PUID")
    pgid = os.getenv("PGID")

    if puid:
        check_call(f'usermod -o -u {puid} coneshare', shell=True)

    if pgid:
        check_call(f'groupmod -o -g {pgid} coneshare', shell=True)


def configure_nginx_real_ip():
    """Dynamically generates /home/coneshare/runtime/nginx/real-ip.conf from TRUSTED_PROXIES."""
    runtime_dir = os.environ.get('RUNTIME_DIR', '/home/coneshare/runtime')
    nginx_dir = os.path.join(runtime_dir, 'nginx')
    os.makedirs(nginx_dir, exist_ok=True)
    real_ip_conf = os.path.join(nginx_dir, 'real-ip.conf')

    trusted_proxies = os.getenv(
        "TRUSTED_PROXIES",
        "127.0.0.1,::1,172.16.0.0/12"
    )
    real_ip_header = os.getenv("REAL_IP_HEADER", "X-Forwarded-For").strip()
    if not re.fullmatch(r"[A-Za-z0-9_-]+", real_ip_header):
        print(f"WARNING: invalid REAL_IP_HEADER {real_ip_header!r}; falling back to X-Forwarded-For")
        real_ip_header = "X-Forwarded-For"

    entries = []
    for raw in trusted_proxies.split(","):
        raw = raw.strip()
        if not raw:
            continue
        try:
            ipaddress.ip_network(raw, strict=False)
            entries.append(raw)
        except ValueError:
            print(f"WARNING: ignoring invalid TRUSTED_PROXIES entry {raw!r}")
            continue

    lines = [
        "# Auto-generated by entrypoint.py from TRUSTED_PROXIES environment variable.",
        "# To customize, set TRUSTED_PROXIES in app.env. Do not edit manually.\n",
    ]

    for ip_range in entries:
        lines.append(f"set_real_ip_from {ip_range};")

    if entries:
        lines.append(f"real_ip_header {real_ip_header};")
        lines.append("real_ip_recursive on;")

    lines.append("")

    with open(real_ip_conf, "w") as f:
        f.write("\n".join(lines))


def main(argv):
    initialize_logdir()
    change_ugid()
    configure_nginx_real_ip()

    app_dir = os.environ['APP_DIR']
    os.chdir(app_dir)

    if argv[1] == 'debug':
        print('Docker image is running, you can attach into the container for debug')
        signal.signal(signal.SIGTERM, lambda s, f: sys.exit(0))
        signal.signal(signal.SIGINT, lambda s, f: sys.exit(0))
        while 1:
            time.sleep(5)
    elif argv[1] == 'coneshare':
        check_call("gosu coneshare bash -c 'rm -rf /tmp/gunicorn.pid'", shell=True)

        supervisord_proc = Popen(
            ["supervisord", "-n", "-c", "/home/coneshare/runtime/supervisord/supervisord.conf"]
        )
        time.sleep(5)
        Popen("tail -f /home/coneshare/logs/*.log", shell=True)

        signal.signal(signal.SIGTERM, lambda s, f: supervisord_proc.terminate())
        signal.signal(signal.SIGINT, lambda s, f: supervisord_proc.terminate())

        sys.exit(supervisord_proc.wait())
    else:
        os.execvp("gosu", ["gosu", "coneshare"] + argv[1:])


if __name__ == "__main__":
    main(sys.argv)
